import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const require = createRequire(import.meta.url);
const outputDirectory = resolve(root, "assets/fonts/open");
const licenseDirectory = resolve(root, "assets/fonts/licenses");
const bundledLicensePath = resolve(root, "assets/fonts/OPEN_FONT_LICENSES.txt");
const themePath = resolve(root, "theme.css");
const startMarker = "/* BEGIN GENERATED OPEN FONT FACES */";
const endMarker = "/* END GENERATED OPEN FONT FACES */";

const variableFamilies = [
  ["geist-sans", "@fontsource-variable/geist", "Claude Geist Sans", ["wght.css", "wght-italic.css"]],
  ["lora", "@fontsource-variable/lora", "Claude Lora", ["wght.css", "wght-italic.css"]],
  ["literata", "@fontsource-variable/literata", "Claude Literata", ["wght.css", "wght-italic.css"]],
  ["source-code-pro", "@fontsource-variable/source-code-pro", "Claude Source Code Pro", ["wght.css", "wght-italic.css"]]
];

await rm(outputDirectory, { recursive: true, force: true });
await rm(licenseDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });
await mkdir(licenseDirectory, { recursive: true });

const generatedFaces = [];
const copiedFiles = new Set();
const bundledLicenses = [];

for (const [id, packageName, familyName, cssFiles] of variableFamilies) {
  const packageRoot = dirname(require.resolve(`${packageName}/package.json`));
  const licensePath = resolve(packageRoot, "LICENSE");
  await copyFile(licensePath, resolve(licenseDirectory, `${id}-OFL-1.1.txt`));
  bundledLicenses.push([
    `FONT FAMILY: ${familyName}`,
    `SOURCE PACKAGE: ${packageName}`,
    "",
    (await readFile(licensePath, "utf8")).trim()
  ].join("\n"));

  for (const cssFile of cssFiles) {
    const css = await readFile(resolve(packageRoot, cssFile), "utf8");
    const facePattern = /\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g;

    for (const match of css.matchAll(facePattern)) {
      const sourceName = match[1].trim();
      if (!sourceName.includes("-cyrillic-") && !sourceName.includes("-latin-")) continue;

      const fontFile = match[2].match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
      if (!fontFile) throw new Error(`No WOFF2 source found in ${packageName}/${cssFile}: ${sourceName}`);

      if (!copiedFiles.has(fontFile)) {
        await copyFile(resolve(packageRoot, "files", fontFile), resolve(outputDirectory, fontFile));
        copiedFiles.add(fontFile);
      }

      const face = match[2]
        .replace(/font-family:\s*'[^']+';/, `font-family: "${familyName}";`)
        .replace(/src:[^;]+;/, `src: url("assets/fonts/open/${fontFile}") format("woff2");`)
        .replaceAll("format('woff2-variations')", 'format("woff2")');
      generatedFaces.push(`/* ${id}: ${sourceName} */\n${face}`);
    }
  }
}

let theme = await readFile(themePath, "utf8");
const start = theme.indexOf(startMarker);
const end = theme.indexOf(endMarker);
if (start < 0 || end < 0 || end < start) throw new Error("Generated font-face markers are missing from theme.css.");

const generatedSection = `${startMarker}\n\n/* Generated by tools/sync-open-fonts.mjs. */\n\n${generatedFaces.join("\n\n")}\n\n${endMarker}`;
theme = `${theme.slice(0, start)}${generatedSection}${theme.slice(end + endMarker.length)}`;
await writeFile(themePath, theme);
await writeFile(
  bundledLicensePath,
  `${bundledLicenses.join(`\n\n${"=".repeat(80)}\n\n`)}\n`
);

console.log(`Synced ${copiedFiles.size} WOFF2 files and ${variableFamilies.length} OFL notices.`);
